/**
 * Emit the feature contract consumed by the Python risk service.
 *
 * The TypeScript registry (modules/analysis/features/registry.ts) is the single
 * authority for what BugDNA measures — it is where the extractors live, so it
 * cannot drift from reality. But the Python service also needs that list: to
 * order the feature vector consistently, to know each feature's neutral fallback,
 * and to give the heuristic scorer its weights.
 *
 * Rather than maintain the list twice, this script serialises it to
 * `contracts/feature-spec.json`, which is committed and read by both services.
 * CI runs this and fails if the output differs from what is checked in, so the
 * two languages cannot disagree about the contract.
 *
 *   npm run contracts:generate   # write
 *   npm run contracts:check      # verify in CI
 */
import fs from "node:fs";
import path from "node:path";
import { FEATURE_SPECS } from "../src/modules/analysis/features/registry";
import { FEATURE_SET_VERSION, RISK_BANDS } from "../src/config/constants";

const OUTPUT = path.resolve(__dirname, "../../contracts/feature-spec.json");

interface Contract {
  $schema: string;
  featureSetVersion: string;
  generatedBy: string;
  description: string;
  riskBands: typeof RISK_BANDS;
  features: Array<{
    key: string;
    label: string;
    description: string;
    category: string;
    type: string;
    unit: string | null;
    fallback: number;
    expectedDirection: string;
    heuristicWeight: number;
    requiresHistory: boolean;
  }>;
}

function buildContract(): Contract {
  return {
    $schema: "https://bugdna.dev/schemas/feature-spec-v1.json",
    featureSetVersion: FEATURE_SET_VERSION,
    generatedBy: "backend/scripts/generate-feature-contract.ts",
    description:
      "Canonical feature contract shared by the BugDNA API and the Python risk service. " +
      "Generated from backend/src/modules/analysis/features/registry.ts — edit that file, " +
      "then run `npm run contracts:generate`. Do not edit this file by hand.",
    riskBands: RISK_BANDS,
    features: FEATURE_SPECS.map((spec) => ({
      key: spec.key,
      label: spec.label,
      description: spec.description,
      category: spec.category,
      type: spec.type,
      unit: spec.unit ?? null,
      fallback: spec.fallback,
      expectedDirection: spec.expectedDirection,
      heuristicWeight: spec.heuristicWeight,
      requiresHistory: spec.requiresHistory ?? false,
    })),
  };
}

function main(): void {
  const check = process.argv.includes("--check");
  const contract = buildContract();
  const serialised = `${JSON.stringify(contract, null, 2)}\n`;

  if (check) {
    if (!fs.existsSync(OUTPUT)) {
      process.stderr.write(
        `\ncontracts/feature-spec.json is missing.\n` +
          `Run \`npm run contracts:generate\` and commit the result.\n\n`,
      );
      process.exit(1);
    }

    const existing = fs.readFileSync(OUTPUT, "utf8");
    if (existing !== serialised) {
      process.stderr.write(
        `\ncontracts/feature-spec.json is out of date with the feature registry.\n` +
          `Run \`npm run contracts:generate\` and commit the result.\n\n`,
      );
      process.exit(1);
    }

    process.stdout.write(
      `contracts/feature-spec.json is up to date ` +
        `(${contract.features.length} features, v${contract.featureSetVersion}).\n`,
    );
    return;
  }

  fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
  fs.writeFileSync(OUTPUT, serialised, "utf8");

  process.stdout.write(
    `Wrote ${path.relative(process.cwd(), OUTPUT)} — ` +
      `${contract.features.length} features, feature set v${contract.featureSetVersion}.\n`,
  );
}

main();
