"""Choose the repositories for the dataset by a rule fixed before any model was trained.

    python -m mining.screen --clones ../pr-risk-radar-mining/repos

A repository qualifies when, before the label cutoff:
  * it has at least --per-repo eligible PRs (squash-merged, human, touching source), and
  * fewer than 10% of its last 1,000 first-parent commits are "Merge pull request"
    merges, i.e. squash merging really is its PR workflow, so git history and the
    GitHub API describe a PR the same way.
The dataset is the first --count qualifying repositories in candidates.txt order.
Per-repository model results play no part in the choice.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from .build_dataset import DEFAULT_CUTOFF
from .gitlog import git

MAX_MERGE_SHARE = 0.10


def merge_share(clone: Path, cutoff: str) -> float:
    out = git(clone, "log", "--first-parent", f"--before={cutoff}", "-1000", "--format=%s").decode(errors="replace")
    subjects = [s for s in out.splitlines() if s]
    return sum(s.startswith("Merge pull request #") for s in subjects) / max(1, len(subjects))


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--candidates", type=Path, default=Path("mining/candidates.txt"))
    ap.add_argument("--clones", type=Path, required=True)
    ap.add_argument("--raw", type=Path, default=Path("data/raw"))
    ap.add_argument("--out", type=Path, default=Path("mining/repos.txt"))
    ap.add_argument("--per-repo", type=int, default=400)
    ap.add_argument("--count", type=int, default=45)
    ap.add_argument("--cutoff", default=DEFAULT_CUTOFF)
    args = ap.parse_args(argv)

    chosen, report = [], []
    for slug in [s.strip() for s in args.candidates.read_text().splitlines() if s.strip() and not s.startswith("#")]:
        name = slug.replace("/", "__")
        clone, stats_path = args.clones / f"{name}.git", args.raw / f"{name}.json"
        if not clone.exists() or (clone / "SKIPPED").exists():
            report.append((slug, "not cloned (size or download failure)"))
            continue
        if not stats_path.exists():
            report.append((slug, "not mined yet"))
            continue
        stats = json.loads(stats_path.read_text())
        share = merge_share(clone, args.cutoff)
        if stats.get("eligible_prs", 0) < args.per_repo:
            report.append((slug, f"only {stats.get('eligible_prs', 0)} eligible PRs"))
        elif share >= MAX_MERGE_SHARE:
            report.append((slug, f"{share:.0%} merge-commit PRs"))
        elif len(chosen) >= args.count:
            report.append((slug, "qualifies; not needed (count reached)"))
        else:
            chosen.append(slug)
            report.append((slug, "selected"))

    for slug, why in report:
        print(f"{slug:36} {why}")
    print(f"\n{len(chosen)} selected (target {args.count})")
    if len(chosen) < args.count:
        print("not enough qualifying repositories yet; repos.txt not written", file=sys.stderr)
        return 1
    args.out.write_text("# Generated by mining/screen.py; see its docstring for the rule.\n" + "\n".join(chosen) + "\n")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
